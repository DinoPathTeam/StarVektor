//! Contracts shared between StarVektor layers.
//!
//! This crate is the only thing every other crate knows about, so it is kept
//! small and stable: data types only, no business logic. If a type is used by a
//! single crate, it lives in that crate and not here.

use core::fmt;

use serde::{Deserialize, Serialize};

/// Regulator level (see D5 and the level table in docs/design.md).
///
/// In the log and in the configuration it is written as an integer (0 to 3).
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default, Serialize, Deserialize,
)]
#[serde(try_from = "u8", into = "u8")]
pub enum Level {
    /// Off: the frame passes through unchanged.
    #[default]
    Off = 0,
    /// All classic: optical flow, HUD rules, heuristic mask.
    Classic = 1,
    /// Classic plus a minimal network for error masking and HUD.
    MiniNet = 2,
    /// Full perception network.
    FullNet = 3,
}

impl Level {
    pub const ALL: [Level; 4] = [Level::Off, Level::Classic, Level::MiniNet, Level::FullNet];

    /// One level up, or the same if already at the maximum.
    #[must_use]
    pub fn up(self) -> Level {
        match self {
            Level::Off => Level::Classic,
            Level::Classic => Level::MiniNet,
            Level::MiniNet | Level::FullNet => Level::FullNet,
        }
    }

    /// One level down, or the same if already `Off`.
    #[must_use]
    pub fn down(self) -> Level {
        match self {
            Level::Off | Level::Classic => Level::Off,
            Level::MiniNet => Level::Classic,
            Level::FullNet => Level::MiniNet,
        }
    }
}

/// Error converting an integer that is not a valid level.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InvalidLevel(pub u8);

impl fmt::Display for InvalidLevel {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "invalid level: {} (expected 0 to 3)", self.0)
    }
}

impl std::error::Error for InvalidLevel {}

impl TryFrom<u8> for Level {
    type Error = InvalidLevel;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        match value {
            0 => Ok(Level::Off),
            1 => Ok(Level::Classic),
            2 => Ok(Level::MiniNet),
            3 => Ok(Level::FullNet),
            other => Err(InvalidLevel(other)),
        }
    }
}

impl From<Level> for u8 {
    fn from(level: Level) -> u8 {
        level as u8
    }
}

/// How the presented frame was obtained.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FrameKind {
    /// Rendered by the game.
    Rendered,
    /// Generated by StarVektor.
    Generated,
    /// The previous frame was repeated (the confidence mask did not trust the result).
    Repeated,
}

/// OptiScaler configuration detected in the chain (D7).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OptiScalerMode {
    #[default]
    None,
    /// Upscaling only.
    Upscale,
    /// Frame generation only.
    Fg,
    /// Upscaling and frame generation.
    Both,
}

/// Which game data is available to StarVektor.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum IntegrationLevel {
    /// The engine provides vectors, depth and layers.
    Engine,
    /// Data arrives through the game's upscaler (with or without OptiScaler).
    Upscaler,
    /// Only the final image is visible.
    ImageOnly,
}

/// Resolution in pixels. Written as `[width, height]`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct Resolution(pub u32, pub u32);

impl Resolution {
    #[must_use]
    pub fn width(self) -> u32 {
        self.0
    }

    #[must_use]
    pub fn height(self) -> u32 {
        self.1
    }
}

/// Milliseconds per StarVektor pass in one frame.
#[derive(Debug, Clone, Copy, PartialEq, Default, Serialize, Deserialize)]
pub struct PassTimings {
    pub capture: f32,
    pub motion: f32,
    pub reproject: f32,
    pub mask: f32,
    pub present: f32,
}

impl PassTimings {
    /// Total StarVektor cost in the frame, in ms.
    #[must_use]
    pub fn total(&self) -> f32 {
        self.capture + self.motion + self.reproject + self.mask + self.present
    }
}

/// Available video memory, in MB.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct MemoryBudget {
    pub used_mb: u32,
    pub free_mb: u32,
}

/// Opaque identifier of a captured frame.
///
/// Pixels never travel between layers: identifiers are passed and each
/// backend resolves the real resource (zero-copy capture).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct FrameHandle(pub u64);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn level_roundtrips_as_integer() {
        for level in Level::ALL {
            let n: u8 = level.into();
            assert_eq!(Level::try_from(n), Ok(level));
        }
        assert_eq!(Level::try_from(4), Err(InvalidLevel(4)));
    }

    #[test]
    fn level_up_down_saturate() {
        assert_eq!(Level::FullNet.up(), Level::FullNet);
        assert_eq!(Level::Off.down(), Level::Off);
        assert_eq!(Level::Off.up(), Level::Classic);
        assert_eq!(Level::Classic.down(), Level::Off);
        assert_eq!(Level::FullNet.down(), Level::MiniNet);
    }

    #[test]
    fn level_orders_by_capability() {
        assert!(Level::Off < Level::Classic);
        assert!(Level::MiniNet < Level::FullNet);
    }

    #[test]
    fn pass_timings_total_sums_passes() {
        let t = PassTimings {
            capture: 0.3,
            motion: 1.0,
            reproject: 0.5,
            mask: 0.4,
            present: 0.2,
        };
        assert!((t.total() - 2.4).abs() < 1e-6);
    }
}
